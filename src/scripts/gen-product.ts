#!/usr/bin/env node
// src/scripts/gen-product.ts — docs/product.md: the library's product description in the form ISO/IEC 25051:2014 5.1
// asks of a ready-to-use software product — identification, work task, functions with the evidence that makes each
// testable, limits and known limitations, support. Every figure is read from the source that holds it (package.json,
// the served catalogue, the ledger, the axiom audit, the lead census), because 25051 5.1.2.3 makes two surfaces that
// state different figures a conformance failure, and a figure typed here would be a second surface.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { spawnSync } from 'node:child_process'
import { ROOT } from './api.js'
import { MCP_CATALOG } from '../mcp.js'
import { theorems, theoremFor, PRINCIPLES } from '../theorems/index.js'
import { HEXBIT_BITS } from '../hexbit/index.js'
import { leadCensus } from '../leads.js'
import { gatherLeads } from './leads-gate.js'
import { doorOfProgram } from '../hex-programs.js'

const json = (rel: string): Record<string, unknown> => JSON.parse(readFileSync(join(ROOT, rel), 'utf8')) as Record<string, unknown>
const pkg = json('package.json') as { name: string; version: string; description: string; license: string; homepage: string; bugs?: { url?: string }; author?: string; dependencies?: Record<string, string>; exports?: Record<string, unknown> }
const axioms = json('lean/axioms.json') as { total?: number; axiomFree?: number }
// the date of the committed tree this description is generated from — the tree, not the clock
const date = spawnSync('git', ['log', '-1', '--format=%cs'], { cwd: ROOT, encoding: 'utf8' }).stdout.trim()
const sealed = theorems().length
const localQubits = HEXBIT_BITS * HEXBIT_BITS // mcp.ts uuidna_quantum: above this a circuit is handed to qpu.uuidna.com
const census = leadCensus(gatherLeads(), doorOfProgram)
const bySource = new Map<string, number>()
for (const l of census.reported) bySource.set(l.source, (bySource.get(l.source) ?? 0) + 1)

// THE PROSE IS LEAN'S (the captain, 2026-11-10: "prose comes from lean inline docs as iso test prompts"). A function is
// the sealed theorems it cites: each theorem's inline doc is the ISO/IEC 25051 test prompt (a statement testable or
// verifiable, 5.1.2.4) and the theorem — kernel-checked, axiom-free — is its test. The heading is the cited wing's own
// principle. Nothing here is typed prose; a function no theorem's doc states is not listed.
const FUNCTIONS: readonly (readonly string[])[] = [
  ['uuidprog_bell_runs', 'uuidprog_ghz_runs', 'uuidprog_toffoli'],
  ['uuidprog_address'],
  ['the_chacha_state_partitions_into_constants_key_counter_and_nonce', 'the_aead_envelope_fits_inside_one_chacha_block', 'pbkdf2_block_count_is_the_ceiling_over_every_length_to_a_kilobit'],
  ['two_coins'],
]
const principleOf = (file: string): string => PRINCIPLES.find((p) => p[0] === file)?.[1] ?? file
const functionRows = FUNCTIONS.map((keys) => {
  const rows = keys.map((k) => theoremFor(k)).filter((t): t is NonNullable<typeof t> => t !== undefined)
  if (rows.length !== keys.length) throw new Error(`gen-product: cites ${keys.filter((k) => !theoremFor(k)).join(', ')}, which the ledger does not seal`)
  return { heading: principleOf(rows[0]!.file), rows }
})

const row = (cells: readonly string[]): string => `| ${cells.join(' | ')} |`
const table = (head: readonly string[], rows: readonly (readonly string[])[]): string =>
  [row(head), `|${head.map(() => '---').join('|')}|`, ...rows.map(row)].join('\n')

const md = `---
title: Product
description: ${pkg.name} ${pkg.version} described as ISO/IEC 25051:2014 5.1 asks of a ready-to-use software product, every figure read from its source.
---

# Product

Generated by \`src/scripts/gen-product.ts\` from \`package.json\`, the served MCP catalogue, the ledger, \`lean/axioms.json\` and
the lead census. Every function below names the evidence that makes it testable; every limit names the condition that
closes it. Figures record what the tree holds, not that it is true
([\`provenance_integrity_not_content_truth\`](/theorem/provenance_integrity_not_content_truth)).

## Identification (5.1.3.1)

${table(['Field', 'Value'], [
  ['Name', `\`${pkg.name}\``],
  ['Version', pkg.version],
  ['Variant', `npm package, ESM, ${Object.keys(pkg.dependencies ?? {}).length} runtime dependencies, ${Object.keys(pkg.exports ?? {}).length} export paths`],
  ['Date', date],
  ['Licence', pkg.license],
])}

## Work task (5.1.3.4)

${pkg.description}

## Functions and their evidence (5.1.2.4, 5.1.5.1)

Measured beside them: ${MCP_CATALOG.length} MCP tools; ${sealed} sealed theorems, ${axioms.axiomFree ?? '?'} of ${axioms.total ?? '?'} audited axiom-free; exact
simulation served locally up to ${localQubits} qubits.

${functionRows.map((f) => `### ${f.heading}\n\n${table(['Test prompt (the theorem\'s Lean doc)', 'Test (the theorem)'], f.rows.map((t) => [String(t.name).replace(/\|/g, '\\|'), `[\`${t.key}\`](/theorem/${t.key})`]))}`).join('\n\n')}

## Limits and known limitations (5.1.5.4)

${census.reported.length} open lead(s) ship as known limitations, each closing when a UUID program decides it (\`run.program\`) or a
verdict settles it:

${table(['Source', 'Open leads'], [...bySource.entries()].sort((a, b) => b[1] - a[1]).map(([s, n]) => [s, String(n)]))}

## Support and maintenance (5.1.3.6, 5.1.3.7)

${table(['Field', 'Value'], [
  ['Repository', pkg.homepage],
  ['Issues', pkg.bugs?.url ?? pkg.homepage],
  ['Maintainer', pkg.author ?? ''],
  ['Releases', 'tagged on GitHub and published to npm through OIDC (`.github/workflows/publish.yml`); each release archived on Zenodo'],
])}
`

writeFileSync(join(ROOT, 'docs', 'product.md'), md)
console.log(`✓ gen-product — ${pkg.name} ${pkg.version}: ${MCP_CATALOG.length} tools, ${sealed} theorems, ${census.reported.length} known limitation(s)`)

#!/usr/bin/env node
// gen-gitattributes — A DERIVED FILE HAS NO MERGE, ONLY A RECOMPUTATION. Every conflict two sessions hit on this
// tree today was in the derived layer — spin-manifest.json four times, a wing manifest, the page seeds — and not one
// of them was a real disagreement: both sides were correct outputs of different sources, and the true value was
// neither, but the regeneration from the merged source. Hand-resolving those is the manual work that cost a 26-step
// rebase that never advanced past step 2. Separate worktrees would only move the collision from the file to the push.
//
// The quantum answer instead: mark the derived layer as UNMERGEABLE and let it collapse by recomputation. Git keeps
// one side rather than raising a conflict, and the very next `reconcile` / `spin --seal` overwrites it with the value
// the merged source actually computes — deterministic, so both sessions land on the same coins. This file is
// GENERATED from DRAIN_PATHS, the one list that already names the derived layer; `one-receipt drain` holds it there.
// The driver is one-time local config (git does not commit it): `npm run setup:git`.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { DRAIN_PATHS, ROOT } from './api.js'

/** Paths a DIRECTORY entry in DRAIN_PATHS sweeps up that NOTHING regenerates — each one authored or deposited,
 *  so a merge that silently keeps one side loses work no recomputation can restore. Declared here rather than
 *  by narrowing DRAIN_PATHS, because that list also decides what reconcile STAGES, and 'lean' genuinely needs
 *  directory staging for the wings. Two questions, two answers.
 *
 *  IT MAY ONLY SHRINK, and it shrinks by giving a path a writer — not by deciding the loss is acceptable. */
const NOT_DERIVED: readonly string[] = [
  'lean/wave-queue.json',         // deposits: mcp.ts writes via depositCandidates, gen-waves only reads
  'lean/leads.json',              // the research record — held / refuted / refused, authored
  'lean/research-ledger.json',    // hand-maintained; its own test calls it "the human record"
  'lean/dormant-scripts.json',    // a roster whose header says it MAY ONLY SHRINK
  'lean/mcp-context-budget.json', // a ceiling re-sealed deliberately, each raise carrying its reason
  'lean/tool-exercise-baseline.json', // a hand-edited debt list
  '.gitattributes',               // the rules: a conflict here settled by coin flip is how this survives its own fix
]

// AND: THE NEWLINE IS PART OF THE ADDRESS. A seal folds file BYTES, and a line ending is a byte. Git's autocrlf —
// which the Windows installer turns on by default — checks the tree out as CRLF while the blobs stay LF, and then
// normalises that same difference away whenever git is asked to compare. So `git status` reports a clean tree while
// `spin --verify` finds 1384 derived files whose coins have every one moved, chunk files nobody has ever opened
// included. The discrepancy is invisible in exactly the place it matters most: every check that reads bytes
// disagrees with every check that asks git, and git is the one that sounds reassuring.
//
// Left to per-clone configuration this returns with every fresh Windows clone, and a law each developer must
// remember is not a law. `text=auto eol=lf` moves it into the repository: every file checks out LF on every host
// whatever autocrlf says, so the bytes a seal folds are the same bytes everywhere — the one-source law, applied to
// the newline.
const body = `# GENERATED by gen-gitattributes from DRAIN_PATHS — do not hand-edit (one-receipt drain holds it).
# THE NEWLINE IS PART OF THE ADDRESS. Seals fold file BYTES, so a CRLF checkout moves every coin while git still
# reports a clean tree (it normalises the ending away when comparing, and never when a generator reads). LF on
# every host, declared by the repository rather than by each clone remembering a local setting.
* text=auto eol=lf

# The derived layer never merges: both sides of a conflict here are correct outputs of different sources, and the
# true value is the recomputation from the merged source. Git keeps one side; reconcile/spin --seal then collapses
# it to the computed value. Enable the driver once per clone: npm run setup:git
${DRAIN_PATHS.map((p) => `${p.endsWith('/') || !p.includes('.') ? p + '/**' : p} merge=derived`).join('\n')}

# ── THE RECORDS UNDER A DIRECTORY ENTRY THAT ARE NOT DERIVED (2026-08-25) ────────────────────────────────────
# A DRAIN_PATHS entry with no dot becomes a DIRECTORY glob above — 'lean' becomes lean/**. That is right for the
# WINGS: every .lean file there is written by its generator, so both sides of a conflict are correct outputs and
# the recomputation settles it. It is far too wide for the hand-maintained JSON living beside them, and the
# driver is not a merge at all: merge.derived.driver is \`true\`, which keeps one side and DISCARDS the other in
# silence, on the promise that a reconcile recomputes the truth. NOTHING recomputes these.
#
# Measured before this list existed: lean/wave-queue.json is a DEPOSIT record — mcp.ts writes it through
# depositCandidates, gen-waves only READS it, and it appears nowhere in reconcile's derive block or generate's
# manifest. One checkout held 462 accepted deposits where origin held 53, and the wings regenerate from a queue
# that no longer names them, so src/firewall, src/knowledge and src/resonance are zero files on origin and
# thirteen sealed theorems went with them. Partial, which is why it went unnoticed: whichever side won lived.
#
# UNSET, NOT RE-CLASSIFIED, and NOT removed from DRAIN_PATHS — the staging behaviour reconcile depends on is a
# separate question from whether a merge may discard a side. \`!merge\` restores the ordinary three-way merge, so
# a real conflict here produces CONFLICT MARKERS an author resolves. A visible conflict is recoverable; a silent
# discard is not.
${NOT_DERIVED.map((p) => `${p} !merge`).join('\n')}
`
writeFileSync(join(ROOT, '.gitattributes'), body)
console.log(`✓ gen-gitattributes — ${DRAIN_PATHS.length} derived paths marked unmergeable (merge=derived); enable with \`npm run setup:git\``)

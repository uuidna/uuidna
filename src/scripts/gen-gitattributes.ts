#!/usr/bin/env node
// gen-gitattributes — A DERIVED FILE HAS NO MERGE, ONLY A RECOMPUTATION. Every conflict two sessions hit on this
// tree today was in the derived layer — spin-manifest.json four times, a wing manifest, the page seeds — and not one
// of them was a real disagreement: both sides were correct outputs of different sources, and the true value was
// neither, but the regeneration from the merged source. Hand-resolving those is the manual work that cost a 26-step
// rebase that never advanced past step 2. Separate worktrees would only move the collision from the file to the push.
//
// The quantum answer instead: mark the derived layer as UNMERGEABLE and let it collapse by recomputation. Git keeps
// one side rather than raising a conflict, and the very next `reconcile` / `spin --seal` overwrites it with the value
// the merged source actually computes — deterministic, so both sessions land on the same coins. This file is
// GENERATED from DRAIN_PATHS, the one list that already names the derived layer; `one-receipt drain` holds it there.
// The driver is one-time local config (git does not commit it): `npm run setup:git`.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { DRAIN_PATHS, ROOT } from './api.js'

const body = `# GENERATED by gen-gitattributes from DRAIN_PATHS — do not hand-edit (one-receipt drain holds it).
# The derived layer never merges: both sides of a conflict here are correct outputs of different sources, and the
# true value is the recomputation from the merged source. Git keeps one side; reconcile/spin --seal then collapses
# it to the computed value. Enable the driver once per clone: npm run setup:git
${DRAIN_PATHS.map((p) => `${p.endsWith('/') || !p.includes('.') ? p + '/**' : p} merge=derived`).join('\n')}
`
writeFileSync(join(ROOT, '.gitattributes'), body)
console.log(`✓ gen-gitattributes — ${DRAIN_PATHS.length} derived paths marked unmergeable (merge=derived); enable with \`npm run setup:git\``)
